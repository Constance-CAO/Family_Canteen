def parse_time(cook_minutes_or_none):
    return cook_minutes_or_none if cook_minutes_or_none else 40


def run():
    with app.app_context():
        # 1. 获取或创建所有需要的大类
        top_cats = {c.name: c for c in Category.query.filter_by(parent_id=0).all()}

        # 确保"蛋"大类存在
        if "蛋" not in top_cats:
            max_order = db.session.query(db.func.max(Category.sort_order)).filter_by(parent_id=0).scalar() or 0
            egg_cat = Category(name="蛋", parent_id=0, sort_order=max_order + 1)
            db.session.add(egg_cat)
            db.session.commit()
            top_cats["蛋"] = egg_cat
            print("已创建大类：蛋")

        # 2. 创建缺失子分类
        all_cats = {c.name: c for c in Category.query.all()}

        for top_name, subs in NEW_SUBCATS.items():
            top_cat = top_cats.get(top_name)
            if not top_cat:
                print(f"警告：找不到大类 {top_name}")
                continue
            for sub_name in subs:
                if sub_name not in all_cats:
                    max_order = db.session.query(db.func.max(Category.sort_order)).filter_by(parent_id=top_cat.id).scalar() or 0
                    new_sub = Category(name=sub_name, parent_id=top_cat.id, sort_order=max_order + 1)
                    db.session.add(new_sub)
                    db.session.commit()
                    all_cats[sub_name] = new_sub
                    print(f"已创建子分类：{top_name} → {sub_name}")

        # 蛋 → 蛋菜
        if "蛋菜" not in all_cats:
            egg_cat = top_cats["蛋"]
            new_sub = Category(name="蛋菜", parent_id=egg_cat.id, sort_order=1)
            db.session.add(new_sub)
            db.session.commit()
            all_cats["蛋菜"] = new_sub
            print("已创建子分类：蛋 → 蛋菜")

        # 刷新 all_cats
        all_cats = {c.name: c for c in Category.query.all()}

        # 3. 插入菜品（同名跳过）
        existing_names = {d.name for d in Dish.query.all()}
        added = skipped = 0

        def insert_dish(row):
            nonlocal added, skipped
            name, sub_name, _, preprocess, cook, bento, ingredients, extra_opts = row
            if name in existing_names:
                skipped += 1
                return
            sub_cat = all_cats.get(sub_name)
            if not sub_cat:
                print(f"警告：找不到子分类 {sub_name}，跳过菜品 {name}")
                return
            dish = Dish(
                name=name,
                category_id=sub_cat.id,
                ingredients=ingredients,
                bento_compatible=bento,
                preprocess_days=preprocess,
                cook_minutes=cook,
                extra_options=json.dumps(extra_opts, ensure_ascii=False),
            )
            db.session.add(dish)
            existing_names.add(name)
            added += 1

        for row in DISHES:
            insert_dish(row)
        for row in EGG_DISHES:
            insert_dish(row)

        db.session.commit()
        print(f"\n导入完成：新增 {added} 道菜品，跳过 {skipped} 道（已存在）。")


if __name__ == "__main__":
    run()
